
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
JOURNAL = ROOT / "journal"

# Each day has a useful engineering topic and a practice task.
TOPICS = [
    (
        "Git fundamentals",
        "Explain the difference between a commit, branch, and tag.",
        "Create a small Git practice repository and inspect its history."
    ),
    (
        "Python testing",
        "Explain why unit tests are useful and what they cannot prove.",
        "Write two tests for a function with normal and edge-case inputs."
    ),
    (
        "HTTP and APIs",
        "Compare HTTP GET and POST, including idempotency.",
        "Document three HTTP status codes and when to use them."
    ),
    (
        "Data structures",
        "Compare lists, stacks, queues, and hash maps.",
        "Implement one small example and state its time complexity."
    ),
    (
        "Software quality",
        "Explain the difference between a bug, a test failure, and a regression.",
        "Write a checklist for reproducing and reporting a bug."
    ),
    (
        "Web performance",
        "Explain caching and the trade-off between freshness and speed.",
        "Inspect a website's network requests and document one observation."
    ),
    (
        "Computer vision",
        "Explain the difference between precision, recall, and mAP.",
        "Write a small example showing why precision and recall can differ."
    ),
    (
        "Reproducible research",
        "Explain why fixed seeds and recorded environments matter.",
        "Draft an experiment log template with configuration and metrics."
    ),
    (
        "Database design",
        "Explain primary keys, foreign keys, and unique constraints.",
        "Design a tiny relational schema for projects and tasks."
    ),
    (
        "Security basics",
        "Explain why secrets should not be committed to source control.",
        "Create a checklist for reviewing environment variables safely."
    ),
    (
        "Algorithms",
        "Compare linear search and binary search and their assumptions.",
        "Trace both algorithms on the same small example."
    ),
    (
        "CI/CD",
        "Explain the difference between continuous integration and deployment.",
        "Sketch a pipeline with linting, tests, and a build step."
    ),
]

def main():
    # Use Bangladesh time so the journal date matches the scheduled run.
    today = datetime.now(ZoneInfo("Asia/Dhaka")).date()
    topic, question, exercise = TOPICS[today.toordinal() % len(TOPICS)]

    JOURNAL.mkdir(parents=True, exist_ok=True)
    output = JOURNAL / f"{today.isoformat()}.md"

    if output.exists():
        print(f"Entry already exists: {output.name}")
        return

    content = f"""# Daily Engineering Journal — {today.isoformat()}

## Topic: {topic}

### Concept to understand

{question}

### Practical exercise

{exercise}

### Reflection

- What did I learn?
- What remains unclear?
- What would I like to test or implement next?

---

This entry was generated by GitHub Evergreen.
The exercise is a suggested task, not a claim that it has been completed.
"""

    output.write_text(content, encoding="utf-8")
    print(f"Created {output.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
